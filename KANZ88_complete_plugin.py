# متغير لتتبع آخر مرة طبعنا فيها الإحداثيات (لطباعتها كل ثانية)
last_position_print = 0

# متغير لتتبع حالة HP السابقة (لتجنب طباعة التحذير بشكل متكرر)
last_hp_warning = False

# رسالة الرد التلقائي على الرسائل الخاصة
AUTO_REPLY_MESSAGE = "Hello"

# ====================================================================================================
# دالة event_loop - تُستدعى بشكل متكرر كل ~500 ميلي ثانية
# ====================================================================================================

def event_loop():
    """
    هذه الدالة تعمل بشكل مستمر ومتكرر
    نستخدمها لمراقبة حالة الشخصية والقيام بإجراءات دورية
    """
    global last_position_print, last_hp_warning
    
    # الحصول على بيانات الشخصية
    character = get_character_data()
    
    if character:
        # ====================================================================================================
        # 1. مراقبة دم الشخصية (HP) - إذا قل عن 50% نطبع تحذير
        # ====================================================================================================
        current_hp = character['hp']
        max_hp = character['max_hp']
        
        if max_hp > 0:
            hp_percent = (current_hp / max_hp) * 100
            
            # إذا كان الدم أقل من 50%
            if hp_percent < 50:
                # نطبع التحذير فقط إذا لم نكن قد طبعناه من قبل (لتجنب التكرار)
                if not last_hp_warning:
                    log(f"⚠️ تحذير! دم الشخصية منخفض: {hp_percent:.1f}% ({current_hp}/{max_hp})")
                    last_hp_warning = True
            else:
                # إذا رجع الدم فوق 50%، نعيد تعيين المتغير للسماح بطباعة التحذير مرة أخرى
                last_hp_warning = False
        
        # ====================================================================================================
        # 2. طباعة إحداثيات الموقع (X, Y, Z) كل ثانية
        # ====================================================================================================
        current_time = time.time()
        
        # نتحقق إذا مر ثانية واحدة أو أكثر منذ آخر طباعة
        if current_time - last_position_print >= 1.0:
            # الحصول على الموقع الحالي للشخصية
            position = get_position()
            
            if position:
                x = position['x']
                y = position['y']
                z = position['z']
                region = position.get('region', 'غير معروف')
                
                log(f"📍 الموقع الحالي - X: {x:.2f}, Y: {y:.2f}, Z: {z:.2f} | المنطقة: {region}")
            
            # تحديث وقت آخر طباعة
            last_position_print = current_time


