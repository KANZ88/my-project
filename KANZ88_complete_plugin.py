def get_character_data():
    """
    دالة مساعدة للحصول على بيانات الشخصية من phBot
    
    ترجع:
        قاموس يحتوي على معلومات الشخصية (الاسم، HP، MP، المستوى، إلخ)
        أو None إذا لم تكن البيانات متاحة
    """
    try:
        # محاولة الحصول على بيانات الشخصية من phBot API
        character = get_character()
        return character
    except Exception:
        # في حالة حدوث خطأ، نرجع None
        return None


def get_position():
    """
    دالة مساعدة للحصول على موقع الشخصية الحالي
    
    ترجع:
        قاموس يحتوي على الإحداثيات (x, y, z) والمنطقة
        أو None إذا لم تكن البيانات متاحة
    """
    try:
        # محاولة الحصول على موقع الشخصية من phBot API
        character = get_character()
        if character:
            position_data = {
                'x': character.get('x', 0),
                'y': character.get('y', 0),
                'z': character.get('z', 0),
                'region': character.get('region', 0)
            }
            return position_data
    except Exception:
        pass
    
    return None


